export function searchAstroTopics(query: string): AstroSearchTopic[] {
  const clean = query.trim().toLowerCase();
  if (!clean) return ASTRO_SEARCH_TOPICS.slice(0, 6);

  const terms = clean.split(/\s+/).filter(Boolean);

  const scored = ASTRO_SEARCH_TOPICS.map((topic) => {
    let score = 0;
    const haystacks = [
      topic.titleTe.toLowerCase(),
      topic.titleEn.toLowerCase(),
      topic.categoryTe.toLowerCase(),
      topic.categoryEn.toLowerCase(),
      topic.descriptionTe.toLowerCase(),
      topic.descriptionEn.toLowerCase(),
      ...topic.keywords.map((k) => k.toLowerCase()),
    ];

    for (const term of terms) {
      if (topic.keywords.some((k) => k.toLowerCase() === term)) {
        score += 25;
      } else if (topic.keywords.some((k) => k.toLowerCase().includes(term))) {
        score += 15;
      }
      if (topic.titleEn.toLowerCase().includes(term) || topic.titleTe.toLowerCase().includes(term)) {
        score += 12;
      }
      if (topic.categoryEn.toLowerCase().includes(term) || topic.categoryTe.toLowerCase().includes(term)) {
        score += 10;
      }
      if (haystacks.some((h) => h.includes(term))) {
        score += 5;
      }
    }

    return { topic, score };
  });

  return scored
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((item) => item.topic);
}
