// Helper to find Nakshatra data by Telugu or English name
export function findNakshatraClassicData(nameQuery: string): NakshatraClassicData | undefined {
  if (!nameQuery) return undefined;
  const q = nameQuery.trim().toLowerCase();

  return NAKSHATRA_CLASSIC_DATA.find((n) => {
    return (
      n.slug.toLowerCase() === q ||
      n.nameEn.toLowerCase() === q ||
      n.nameTe.toLowerCase().includes(q) ||
      q.includes(n.nameTe.toLowerCase()) ||
      q.includes(n.slug.toLowerCase())
    );
  });
}

// Helper to find Tithi data by query
export function findTithiClassicData(tithiQuery: string): TithiClassicData | undefined {
  if (!tithiQuery) return undefined;
  const q = tithiQuery.trim().toLowerCase();

  return TITHI_CLASSIC_DATA.find((t) => {
    return (
      t.nameTe.toLowerCase().includes(q) ||
      q.includes(t.nameTe.toLowerCase()) ||
      t.nameEn.toLowerCase() === q
    );
  });
}
